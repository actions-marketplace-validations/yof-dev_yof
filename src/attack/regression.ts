/**
 * yof attack, feature A: every CONFIRMED finding becomes a regression test in the repository's own test framework,
 * built from the recorded attack with the expectation inverted (what worked for the attacker must fail from now on).
 * Deterministic: a template and the recorded steps, no AI.
 *
 * Framework, detected from the repository's own files, first match wins:
 *   vitest      "vitest" in package.json, or a vitest.config.*
 *   jest        "jest" in package.json, or a jest.config.*
 *   playwright  "@playwright/test" in package.json, or a playwright.config.* (the file goes into its testDir)
 *   pytest      pytest.ini, conftest.py, [tool.pytest...] in pyproject.toml, or pytest in requirements*.txt
 *   generic     anything else: a node:test file (`node --test`), no dependency at all
 *
 * Each test skips itself unless YOF_ATTACK_TARGET is set, so the repository's ordinary test run is not affected.
 * Credentials come from the same environment variables the config names; a test never contains one.
 */
import { createHash } from "node:crypto";
import { REPLAY_ENGINE_JS, type ReplaySpec } from "./replay";

export type Framework = "vitest" | "jest" | "playwright" | "pytest" | "generic";
export const GENERATED_MARK = "Generated by yof attack from a recorded finding.";
export const GENERATED_LINE = `${GENERATED_MARK} Re-run yof attack to update it; it fails while the attack still works.`;

export interface RepoReader { read: (path: string) => string | null; exists: (path: string) => boolean }

const CONFIG = (name: string, r: RepoReader) => ["ts", "mts", "cts", "js", "mjs", "cjs"].some((e) => r.exists(`${name}.config.${e}`));

export function detectFramework(r: RepoReader): { framework: Framework; dir: string } {
  let pkg: { dependencies?: Record<string, string>; devDependencies?: Record<string, string> } = {};
  try { pkg = JSON.parse(r.read("package.json") ?? "{}"); } catch { pkg = {}; }
  const deps = { ...(pkg.dependencies ?? {}), ...(pkg.devDependencies ?? {}) };
  if ("vitest" in deps || CONFIG("vitest", r)) return { framework: "vitest", dir: "yof-attack" };
  if ("jest" in deps || CONFIG("jest", r)) return { framework: "jest", dir: "yof-attack" };
  if ("@playwright/test" in deps || CONFIG("playwright", r)) {
    const cfg = ["ts", "js", "mjs", "cjs"].map((e) => r.read(`playwright.config.${e}`)).find((x) => x != null) ?? "";
    const dir = /testDir\s*:\s*["'`]\.?\/?([\w./-]+?)\/?["'`]/.exec(cfg)?.[1] ?? "tests";
    return { framework: "playwright", dir: `${dir.replace(/^\.\/?/, "") || "tests"}/yof-attack` };
  }
  const py = r.read("pyproject.toml") ?? "";
  const reqs = ["requirements.txt", "requirements-dev.txt", "requirements_dev.txt"].map((p) => r.read(p) ?? "").join("\n");
  if (r.exists("pytest.ini") || r.exists("conftest.py") || /\[tool\.pytest/.test(py) || /^\s*pytest\b/im.test(reqs)) return { framework: "pytest", dir: "tests" };
  return { framework: "generic", dir: "yof-attack" };
}

const slug = (s: string) => s.toLowerCase().replace(/[{}]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40);
export function testName(spec: ReplaySpec, route: string, method: string): string {
  const h = createHash("sha256").update(`${spec.ruleId}|${method}|${route}`).digest("hex").slice(0, 6);
  return `${slug(spec.ruleId.replace(/^attack\./, ""))}-${slug(route) || "root"}-${h}`;
}

const JS_SPEC = (spec: ReplaySpec) => `const spec = ${JSON.stringify(spec, null, 2)};`;
const label = (spec: ReplaySpec, method: string, route: string) => JSON.stringify(`${spec.ruleId}: ${method} ${route} stays fixed`);

export interface GeneratedTest { path: string; framework: Framework; content: string; ruleId: string }

export function synthesizeTest(spec: ReplaySpec, where: { method: string; route: string }, fw: { framework: Framework; dir: string }): GeneratedTest {
  const name = testName(spec, where.route, where.method);
  const title = JSON.stringify(`yof attack: ${spec.title}`);
  const it = label(spec, where.method, where.route);
  const engine = REPLAY_ENGINE_JS.trim();
  let path: string, content: string;
  switch (fw.framework) {
    case "vitest":
      path = `${fw.dir}/${name}.yof-attack.test.ts`;
      content = [`// ${GENERATED_LINE}`, "// @ts-nocheck", 'import { describe, expect, it } from "vitest";', "", JS_SPEC(spec), "", engine, "",
        `describe.skipIf(!process.env.YOF_ATTACK_TARGET)(${title}, () => {`,
        `  it(${it}, async () => {`, "    expect(await yofReplay(spec, process.env)).toEqual([]);", "  }, 60_000);", "});", ""].join("\n");
      break;
    case "jest":
      path = `${fw.dir}/${name}.yof-attack.test.js`;
      content = [`// ${GENERATED_LINE}`, "", JS_SPEC(spec), "", engine, "",
        `(process.env.YOF_ATTACK_TARGET ? describe : describe.skip)(${title}, () => {`,
        `  it(${it}, async () => {`, "    expect(await yofReplay(spec, process.env)).toEqual([]);", "  }, 60000);", "});", ""].join("\n");
      break;
    case "playwright":
      path = `${fw.dir}/${name}.yof-attack.spec.ts`;
      content = [`// ${GENERATED_LINE}`, "// @ts-nocheck", 'import { expect, test } from "@playwright/test";', "", JS_SPEC(spec), "", engine, "",
        `test.describe(${title}, () => {`, '  test.skip(!process.env.YOF_ATTACK_TARGET, "Set YOF_ATTACK_TARGET to run the yof attack regression tests.");',
        `  test(${it}, async () => {`, "    test.setTimeout(60_000);", "    expect(await yofReplay(spec, process.env)).toEqual([]);", "  });", "});", ""].join("\n");
      break;
    case "pytest": {
      const fn = `test_yof_attack_${name.replace(/-/g, "_")}`;
      path = `${fw.dir}/test_yof_attack_${name.replace(/-/g, "_")}.py`;
      content = [`# ${GENERATED_LINE}`, PY_ENGINE.trim(), "", `SPEC = json.loads(${JSON.stringify(JSON.stringify(spec))})`, "", "",
        "@_yof_skip", `def ${fn}():`, `    """${spec.title.replace(/"/g, "'")}"""`, "    assert _yof_replay(SPEC, os.environ) == []", "", "",
        'if __name__ == "__main__":', `    ${fn}()`, '    print("ok")', ""].join("\n");
      break;
    }
    default:
      path = `${fw.dir}/${name}.yof-attack.test.mjs`;
      content = [`// ${GENERATED_LINE}`, "// Run with: node --test", 'import { test } from "node:test";', 'import assert from "node:assert/strict";', "", JS_SPEC(spec), "", engine, "",
        `test(${it}, { skip: !process.env.YOF_ATTACK_TARGET && "Set YOF_ATTACK_TARGET to run it", timeout: 60000 }, async () => {`,
        "  assert.deepEqual(await yofReplay(spec, process.env), []);", "});", ""].join("\n");
  }
  return { path, framework: fw.framework, content, ruleId: spec.ruleId };
}

/** The Python twin of REPLAY_ENGINE_JS (same steps, same expectations), standard library only. */
export const PY_ENGINE = String.raw`
import http.client
import json
import os
import random
import re
import string
import urllib.parse

try:
    import pytest
    _yof_skip = pytest.mark.skipif(not os.environ.get("YOF_ATTACK_TARGET"), reason="Set YOF_ATTACK_TARGET to run it")
except ImportError:
    def _yof_skip(f):
        return f

_IMPERATIVE = re.compile(r"\b(never|always|do not|don't|must|you should|only answer|keep (?:replies|answers)|under \d+ sentences|refuse)\b", re.I)
_SAYS = re.compile(r"\b(?:" + " ".join(["system", "prompt"]) + r"|my (?:instructions|guidelines) (?:are|say)|here (?:are|is) my (?:instructions|prompt))\b", re.I)


def _yof_replay(spec, env):
    base = (env.get("YOF_ATTACK_TARGET") or "").rstrip("/")
    if not base:
        raise RuntimeError("Set YOF_ATTACK_TARGET to the address of the app under test.")
    vs = {v: "yof" + v + "".join(random.choice(string.ascii_lowercase + string.digits) for _ in range(10)) for v in spec["vars"]}

    def J(s):
        return json.dumps("" if s is None else str(s))[1:-1]

    def sub(s, how):
        return re.sub(r"\{\{(\w+)\}\}", lambda m: how(vs[m.group(1)]) if m.group(1) in vs else m.group(0), s)

    def as_text(v):
        if isinstance(v, str):
            return v
        if v is None:
            return ""
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, int):
            return str(v)
        return json.dumps(v, separators=(",", ":"))

    def pick(text, path):
        try:
            v = json.loads(text)
        except Exception:
            return text
        for p in path.split("."):
            if v is None:
                return ""
            if isinstance(v, list) and p.isdigit():
                v = v[int(p)] if int(p) < len(v) else None
            elif isinstance(v, dict):
                v = v.get(p)
            else:
                v = None
        return as_text(v)

    def leaves(text):
        out = []
        try:
            v = json.loads(text)
        except Exception:
            return out

        def walk(x):
            if isinstance(x, str) and 6 <= len(x) <= 120:
                out.append(x)
            elif isinstance(x, dict):
                for k in x:
                    walk(x[k])
            elif isinstance(x, list):
                for k in x:
                    walk(k)
        walk(v)
        return out

    def distinct(a, b):
        return next((x for x in leaves(a or "") if x not in (b or "")), "")

    def instructions(r):
        r = r[:20000]
        if len(r) < 250:
            return False
        n = len(_IMPERATIVE.findall(r))
        if re.search(r"\byou are\b", r, re.I) and n >= 3:
            return True
        return bool(_SAYS.search(r)) and n >= 2 and len(r) >= 400

    def ok(s):
        return 200 <= s < 300

    def request(method, path, headers, body):
        u = urllib.parse.urlsplit(base + path)
        conn = (http.client.HTTPSConnection if u.scheme == "https" else http.client.HTTPConnection)(u.hostname, u.port, timeout=20)
        target = (u.path or "/") + ("?" + u.query if u.query else "")
        conn.request(method, target, body=None if body is None else body.encode("utf-8"), headers=headers)
        r = conn.getresponse()
        res = {"status": r.status, "text": r.read().decode("utf-8", "replace"),
               "headers": {k.lower(): v for k, v in r.getheaders()}, "cookies": r.msg.get_all("Set-Cookie") or []}
        conn.close()
        return res

    auth = {}

    def login(role, wrong):
        acc = spec["accounts"][role]
        pw = vs.get("wrong", "yof-wrong") if wrong else env.get(acc["passwordEnv"])
        body = acc["login"]["body"].replace("{{email}}", J(env.get(acc["emailEnv"]))).replace("{{password}}", J(pw))
        return request("POST", acc["login"]["path"], {"Content-Type": "application/json", "Accept": "application/json"}, body)

    def headers_for(who):
        if who == "anon":
            return {}
        if who in auth:
            return auth[who]
        acc = spec["accounts"].get(who)
        if not acc:
            raise RuntimeError("This test needs account " + who + ".")
        if "env" in acc:
            if not env.get(acc["env"]):
                raise RuntimeError("Set " + acc["env"] + ".")
            auth[who] = {acc["header"]: env[acc["env"]]}
            return auth[who]
        if not env.get(acc["emailEnv"]) or not env.get(acc["passwordEnv"]):
            raise RuntimeError("Set " + acc["emailEnv"] + " and " + acc["passwordEnv"] + ".")
        r = login(who, False)
        if not ok(r["status"]):
            raise RuntimeError("Sign-in for account " + who + " failed (HTTP " + str(r["status"]) + ").")
        if acc["login"].get("tokenPath"):
            auth[who] = {acc["login"].get("header", "Authorization"): acc["login"].get("prefix", "") + pick(r["text"], acc["login"]["tokenPath"])}
        else:
            auth[who] = {"Cookie": "; ".join(c.split(";")[0] for c in r["cookies"] if c)}
        return auth[who]

    def run(st):
        statuses = []
        last = None
        for _ in range(st.get("repeat") or 1):
            if st.get("login"):
                last = login(st["login"]["role"], st["login"]["wrong"])
                statuses.append(last["status"])
                continue
            h = {"Accept": "application/json"}
            h.update(headers_for(st["as"]))
            h.update(st.get("headers") or {})
            body = None
            if "body" in st:
                h["Content-Type"] = "application/json"
                body = sub(st["body"], J)
            last = request(st["method"], sub(st["path"], lambda v: urllib.parse.quote(str(v), safe="")), h, body)
            statuses.append(last["status"])
        return last, statuses

    failures = []
    cleanups = []
    try:
        for st in spec["steps"]:
            if "derive" in st:
                d = st["derive"]
                vs[d["name"]] = distinct(vs.get(d["from"][0]), vs.get(d["from"][1]))
                continue
            if st.get("cleanup"):
                cleanups.append(st)
                continue
            last, statuses = run(st)
            if st.get("setup") and not ok(last["status"]):
                raise RuntimeError("Setup step " + st["method"] + " " + st["path"] + " answered HTTP " + str(last["status"]) + ".")
            if st.get("save"):
                vs[st["save"]["name"]] = pick(last["text"], st["save"]["from"])
            if st.get("keep"):
                vs[st["keep"]] = last["text"]
            e = st.get("expect")
            if not e:
                continue
            text = pick(last["text"], st["replyPath"]) if st.get("replyPath") else last["text"]
            where = st["method"] + " " + st["path"] + " as " + st["as"]
            k = e["kind"]
            if k == "denied" and ok(last["status"]):
                failures.append(where + " should be refused, got HTTP " + str(last["status"]))
            if k == "not_contains":
                v = sub(e["value"], str)
                if v and ok(last["status"]) and v in text:
                    failures.append(where + " returned data it must not return")
            if k == "not_redirect_to":
                loc = last["headers"].get("location", "")
                host = urllib.parse.urlsplit(urllib.parse.urljoin(base + "/", loc)).hostname if loc else ""
                if 300 <= last["status"] < 400 and host == e["host"]:
                    failures.append(where + " redirects to " + e["host"])
            if k == "header_present" and not last["headers"].get(e["name"]):
                failures.append(where + " has no " + e["name"] + " header")
            if k == "not_instructions" and ok(last["status"]) and instructions(text):
                failures.append(where + " gave out its hidden instructions")
            if k == "some_status" and not any(s in e["status"] for s in statuses):
                failures.append(where + " was never slowed down (" + str(len(statuses)) + " tries)")
            if k == "cookie_flags":
                weak = [c for c in last["cookies"] if not re.search(r";\s*httponly", c, re.I) or not re.search(r";\s*samesite=", c, re.I)
                        or (base.startswith("https:") and not re.search(r";\s*secure", c, re.I))]
                if weak:
                    failures.append(where + " sets a cookie without HttpOnly, SameSite or Secure")
    finally:
        for st in cleanups:
            try:
                run(st)
            except Exception:
                pass
    return failures
`;
