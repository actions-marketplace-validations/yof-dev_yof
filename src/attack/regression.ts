/**
 * yof attack, feature A: every CONFIRMED finding becomes a regression test in the repository's own test framework,
 * built from the recorded attack with the expectation inverted (what worked for the attacker must fail from now on).
 * Deterministic: a template and the recorded steps, no AI.
 *
 * Framework, detected from the repository's own files, first match wins:
 *   vitest      "vitest" in package.json, or a vitest.config.*
 *   jest        "jest" in package.json, or a jest.config.*
 *   playwright  "@playwright/test" in package.json, or a playwright.config.* (the file goes into its testDir)
 *   pytest      pytest.ini, conftest.py, [tool.pytest...] in pyproject.toml, or pytest in requirements*.txt
 *   generic     anything else: a node:test file (`node --test`), no dependency at all
 *
 * Each test skips itself unless YOF_ATTACK_TARGET is set, so the repository's ordinary test run is not affected.
 * Credentials come from the same environment variables the config names; a test never contains one.
 */
import { createHash } from "node:crypto";
import { REPLAY_ENGINE_JS, type ReplaySpec } from "./replay";

export type Framework = "vitest" | "jest" | "playwright" | "pytest" | "generic";
export const GENERATED_MARK = "Generated by yof attack from a recorded finding.";
export const GENERATED_LINE = `${GENERATED_MARK} Re-run yof attack to update it; it fails while the attack still works.`;

export interface RepoReader { read: (path: string) => string | null; exists: (path: string) => boolean }

const CONFIG = (name: string, r: RepoReader) => ["ts", "mts", "cts", "js", "mjs", "cjs"].some((e) => r.exists(`${name}.config.${e}`));

export function detectFramework(r: RepoReader): { framework: Framework; dir: string } {
  let pkg: { dependencies?: Record<string, string>; devDependencies?: Record<string, string> } = {};
  try { pkg = JSON.parse(r.read("package.json") ?? "{}"); } catch { pkg = {}; }
  const deps = { ...(pkg.dependencies ?? {}), ...(pkg.devDependencies ?? {}) };
  if ("vitest" in deps || CONFIG("vitest", r)) return { framework: "vitest", dir: "yof-attack" };
  if ("jest" in deps || CONFIG("jest", r)) return { framework: "jest", dir: "yof-attack" };
  if ("@playwright/test" in deps || CONFIG("playwright", r)) {
    const cfg = ["ts", "js", "mjs", "cjs"].map((e) => r.read(`playwright.config.${e}`)).find((x) => x != null) ?? "";
    const dir = /testDir\s*:\s*["'`]\.?\/?([\w./-]+?)\/?["'`]/.exec(cfg)?.[1] ?? "tests";
    return { framework: "playwright", dir: `${dir.replace(/^\.\/?/, "") || "tests"}/yof-attack` };
  }
  const py = r.read("pyproject.toml") ?? "";
  const reqs = ["requirements.txt", "requirements-dev.txt", "requirements_dev.txt"].map((p) => r.read(p) ?? "").join("\n");
  if (r.exists("pytest.ini") || r.exists("conftest.py") || /\[tool\.pytest/.test(py) || /^\s*pytest\b/im.test(reqs)) return { framework: "pytest", dir: "tests" };
  return { framework: "generic", dir: "yof-attack" };
}

const slug = (s: string) => s.toLowerCase().replace(/[{}]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40);
export function testName(spec: ReplaySpec, route: string, method: string): string {
  const h = createHash("sha256").update(`${spec.ruleId}|${method}|${route}`).digest("hex").slice(0, 6);
  return `${slug(spec.ruleId.replace(/^attack\./, ""))}-${slug(route) || "root"}-${h}`;
}

const JS_SPEC = (spec: ReplaySpec) => `const spec = ${JSON.stringify(spec, null, 2)};`;
const label = (spec: ReplaySpec, method: string, route: string) => JSON.stringify(`${spec.ruleId}: ${method} ${route} stays fixed`);

export interface GeneratedTest { path: string; framework: Framework; content: string; ruleId: string }

export function synthesizeTest(spec: ReplaySpec, where: { method: string; route: string }, fw: { framework: Framework; dir: string }): GeneratedTest {
  const name = testName(spec, where.route, where.method);
  const title = JSON.stringify(`yof attack: ${spec.title}`);
  const it = label(spec, where.method, where.route);
  const engine = REPLAY_ENGINE_JS.trim();
  let path: string, content: string;
  switch (fw.framework) {
    case "vitest":
      path = `${fw.dir}/${name}.yof-attack.test.ts`;
      content = [`// ${GENERATED_LINE}`, "// @ts-nocheck", 'import { describe, expect, it } from "vitest";', "", JS_SPEC(spec), "", engine, "",
        `describe.skipIf(!process.env.YOF_ATTACK_TARGET)(${title}, () => {`,
        `  it(${it}, async () => {`, "    expect(await yofReplay(spec, process.env)).toEqual([]);", "  }, 60_000);", "});", ""].join("\n");
      break;
    case "jest":
      path = `${fw.dir}/${name}.yof-attack.test.js`;
      content = [`// ${GENERATED_LINE}`, "", JS_SPEC(spec), "", engine, "",
        `(process.env.YOF_ATTACK_TARGET ? describe : describe.skip)(${title}, () => {`,
        `  it(${it}, async () => {`, "    expect(await yofReplay(spec, process.env)).toEqual([]);", "  }, 60000);", "});", ""].join("\n");
      break;
    case "playwright":
      path = `${fw.dir}/${name}.yof-attack.spec.ts`;
      content = [`// ${GENERATED_LINE}`, "// @ts-nocheck", 'import { expect, test } from "@playwright/test";', "", JS_SPEC(spec), "", engine, "",
        `test.describe(${title}, () => {`, '  test.skip(!process.env.YOF_ATTACK_TARGET, "Set YOF_ATTACK_TARGET to run the yof attack regression tests.");',
        `  test(${it}, async () => {`, "    test.setTimeout(60_000);", "    expect(await yofReplay(spec, process.env)).toEqual([]);", "  });", "});", ""].join("\n");
      break;
    case "pytest": {
      const fn = `test_yof_attack_${name.replace(/-/g, "_")}`;
      path = `${fw.dir}/test_yof_attack_${name.replace(/-/g, "_")}.py`;
      content = [`# ${GENERATED_LINE}`, PY_ENGINE.trim(), "", `SPEC = json.loads(${JSON.stringify(JSON.stringify(spec))})`, "", "",
        "@_yof_skip", `def ${fn}():`, `    """${spec.title.replace(/"/g, "'")}"""`, "    assert _yof_replay(SPEC, os.environ) == []", "", "",
        'if __name__ == "__main__":', `    ${fn}()`, '    print("ok")', ""].join("\n");
      break;
    }
    default:
      path = `${fw.dir}/${name}.yof-attack.test.mjs`;
      content = [`// ${GENERATED_LINE}`, "// Run with: node --test", 'import { test } from "node:test";', 'import assert from "node:assert/strict";', "", JS_SPEC(spec), "", engine, "",
        `test(${it}, { skip: !process.env.YOF_ATTACK_TARGET && "Set YOF_ATTACK_TARGET to run it", timeout: 60000 }, async () => {`,
        "  assert.deepEqual(await yofReplay(spec, process.env), []);", "});", ""].join("\n");
  }
  return { path, framework: fw.framework, content, ruleId: spec.ruleId };
}

